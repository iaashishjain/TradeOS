"use client";

import { formatCurrency, formatPrice, num, resultLabel } from "@/lib/calculations";
import type { Trade, Playbook, DailyReview } from "@/db/schema";

// ── Colors ──
const C = {
  primary: [99, 102, 241] as [number, number, number],
  profit: [34, 197, 94] as [number, number, number],
  loss: [239, 68, 68] as [number, number, number],
  text: [55, 65, 81] as [number, number, number],
  muted: [107, 114, 128] as [number, number, number],
  light: [245, 245, 250] as [number, number, number],
  white: [255, 255, 255] as [number, number, number],
  headerBg: [30, 30, 45] as [number, number, number],
};

// ── Helpers ──
function fDate(d: Date | string | null | undefined): string {
  if (!d) return "—";
  return new Date(d).toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });
}
function fTime(d: Date | string | null | undefined): string {
  if (!d) return "";
  return new Date(d).toLocaleTimeString("en-US", { hour: "2-digit", minute: "2-digit", hour12: false });
}
function sesLbl(s: string | null | undefined): string {
  if (!s) return "—";
  return s.replace("_", " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

// Dynamic loader so jsPDF is only loaded client-side at call time
async function loadLibs() {
  const jspdfMod = await import("jspdf");
  const atMod = await import("jspdf-autotable");
  const JsPDF = (jspdfMod as any).jsPDF || jspdfMod.default;
  const at = (atMod as any).default || (atMod as any).autoTable || atMod;
  return { JsPDF: JsPDF as typeof jspdfMod.default, autoTable: at as (doc: any, opts: any) => void };
}

function downloadBlob(doc: { output: (t: string) => Blob }, filename: string) {
  const blob = doc.output("blob") as Blob;
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.style.display = "none";
  document.body.appendChild(a);
  a.click();
  setTimeout(() => {
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }, 300);
}

// Shared PDF building helpers operating on any jsPDF instance
function addHeader(doc: any, title: string, subtitle: string) {
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(...C.headerBg);
  doc.rect(0, 0, w, 22, "F");
  doc.setFontSize(14);
  doc.setTextColor(...C.white);
  doc.setFont("helvetica", "bold");
  doc.text("TradeOS", 10, 10);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(title, 10, 17);
  doc.setFontSize(8);
  doc.setTextColor(180, 180, 200);
  doc.text(subtitle, w - 10, 10, { align: "right" });
  doc.text(new Date().toLocaleString("en-US", { year: "numeric", month: "long", day: "numeric", hour: "2-digit", minute: "2-digit" }), w - 10, 16, { align: "right" });
}

function addFooter(doc: any) {
  const pages = doc.internal.pages.length - 1;
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(7);
    doc.setTextColor(...C.muted);
    doc.text(`Page ${i} of ${pages}`, w / 2, h - 5, { align: "center" });
    doc.text("Generated by TradeOS", 10, h - 5);
  }
}

function secTitle(doc: any, y: number, title: string): number {
  const w = doc.internal.pageSize.getWidth();
  doc.setFontSize(11);
  doc.setTextColor(...C.primary);
  doc.setFont("helvetica", "bold");
  doc.text(title, 10, y);
  doc.setDrawColor(...C.primary);
  doc.setLineWidth(0.3);
  doc.line(10, y + 1.5, w - 10, y + 1.5);
  return y + 7;
}

function kpiRow(doc: any, y: number, items: { label: string; value: string; color?: [number, number, number] }[]): number {
  const w = doc.internal.pageSize.getWidth() - 20;
  const bw = w / items.length;
  for (let i = 0; i < items.length; i++) {
    const x = 10 + i * bw;
    doc.setFillColor(...C.light);
    doc.roundedRect(x + 1, y, bw - 2, 14, 2, 2, "F");
    doc.setFontSize(10);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...(items[i].color || C.text));
    doc.text(items[i].value, x + bw / 2, y + 6, { align: "center" });
    doc.setFontSize(6);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(...C.muted);
    doc.text(items[i].label.toUpperCase(), x + bw / 2, y + 11, { align: "center" });
  }
  return y + 18;
}

function needsBreak(doc: any, y: number, needed: number): boolean {
  return y + needed > doc.internal.pageSize.getHeight() - 15;
}

