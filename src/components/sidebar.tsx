export function Sidebar() {
  const pathname = usePathname();
  const [open, setOpen] = useState(false);

  // Register the global open trigger
  useEffect(() => { openSidebar = () => setOpen(true); return () => { openSidebar = null; }; }, []);

  // Close drawer whenever the route changes
  useEffect(() => { setOpen(false); }, [pathname]);

  // Close on Escape key
  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => { if (e.key === "Escape") setOpen(false); };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open]);

  // Lock body scroll while drawer is open
  useEffect(() => {
    document.body.style.overflow = open ? "hidden" : "";
    return () => { document.body.style.overflow = ""; };
  }, [open]);

  const close = useCallback(() => setOpen(false), []);

  return (
    <>
      {/* Hamburger — inline, not fixed. Rendered by PageShell via MenuButton export */}

      {/* Backdrop overlay */}
      <div
        className={`fixed inset-0 z-40 bg-black/60 backdrop-blur-[2px] transition-opacity duration-200 ${open ? "opacity-100" : "opacity-0 pointer-events-none"}`}
        onClick={close}
        aria-hidden="true"
      />

      {/* Drawer panel — slides from right */}
      <aside
        className={`fixed top-0 right-0 z-50 h-full w-[260px] bg-dark-950/95 backdrop-blur-xl border-l border-white/5 flex flex-col transition-transform duration-200 ease-out will-change-transform ${
          open ? "translate-x-0" : "translate-x-full"
        }`}
      >
        {/* Header */}
        <div className="p-5 flex items-center justify-between border-b border-white/5">
          <div className="flex items-center gap-3">
            <div className="w-8 h-8 rounded-lg bg-gradient-to-br from-accent-500 to-purple-600 flex items-center justify-center">
              <svg className="w-4 h-4 text-white" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M2.25 18 9 11.25l4.306 4.306a11.95 11.95 0 0 1 5.814-5.518l2.74-1.22" />
              </svg>
            </div>
            <div>
              <h1 className="text-sm font-bold text-white">TradeOS</h1>
              <p className="text-[10px] text-dark-400">Performance OS</p>
            </div>
          </div>
          <button onClick={close} className="p-1.5 rounded-lg text-dark-400 hover:text-white hover:bg-white/10 active:scale-95 transition-all" aria-label="Close menu">
            <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M6 18L18 6M6 6l12 12" />
            </svg>
          </button>
        </div>

        {/* Nav links */}
        <nav className="flex-1 p-3 space-y-0.5 overflow-y-auto" aria-label="Main navigation">
          {navItems.map((item) => {
            const isActive = item.href === "/" ? pathname === "/" : pathname.startsWith(item.href);
            return (
              <Link
                key={item.href}
                href={item.href}
                onClick={close}
                prefetch={true}
                className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm transition-colors duration-100 ${
                  isActive
                    ? "bg-accent-500/15 text-accent-400"
                    : "text-dark-300 hover:text-white hover:bg-white/5 active:bg-white/10"
                }`}
                aria-current={isActive ? "page" : undefined}
              >
                <span className={isActive ? "text-accent-400" : "text-dark-400"}>{item.icon}</span>
                <span className="font-medium">{item.label}</span>
              </Link>
            );
          })}
        </nav>

        <div className="p-4 border-t border-white/5">
          <p className="text-[10px] text-dark-500 text-center">TradeOS v1.0</p>
        </div>
      </aside>
    </>
  );
}
